"""Generate contracts and TS types. Run --check in CI to detect drift."""

import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app import schemas
from app.main import app
from app.docgen import FHIR_LITE_SCHEMA

models = [
    schemas.Word,
    schemas.ExtractRequest,
    schemas.Dose,
    schemas.Evidence,
    schemas.ClinicalEvent,
    schemas.SaveRecordRequest,
    schemas.Record,
    schemas.Transcript,
    schemas.ErrorEnvelope,
]
defs = {}
for model in models:
    schema = model.model_json_schema(ref_template="#/$defs/{model}")
    defs.update(schema.pop("$defs", {}))
    defs[model.__name__] = schema


def ts(s):
    if isinstance(s, bool):
        return "unknown"
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "const" in s:
        return json.dumps(s["const"])
    if "anyOf" in s:
        return " | ".join(ts(v) for v in s["anyOf"])
    kind = s.get("type")
    if kind == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts(v) for v in s["prefixItems"]) + "]"
        return "(" + ts(s.get("items", {})) + ")[]"
    if kind == "object":
        props = s.get("properties")
        if props is not None:
            return (
                "{\n"
                + "\n".join(
                    "  "
                    + json.dumps(k)
                    + ("" if k in s.get("required", []) else "?")
                    + ": "
                    + ts(v)
                    + ";"
                    for k, v in props.items()
                )
                + "\n}"
            )
        return "{[key: string]: " + ts(s.get("additionalProperties", {})) + "}"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


types = "// Generated by tools/contracts.py. Do not edit.\n" + "\n\n".join(
    "export type " + name + " = " + ts(schema) + ";" for name, schema in defs.items()
)
outputs = {
    ROOT / "contracts/schemas.json": json.dumps(
        {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": defs},
        indent=2,
    )
    + "\n",
    ROOT / "contracts/openapi.json": json.dumps(app.openapi(), indent=2) + "\n",
    ROOT / "contracts/fhir-lite.schema.json": json.dumps(FHIR_LITE_SCHEMA, indent=2)
    + "\n",
    ROOT / "frontend/src/generated.ts": types + "\n",
}
check = "--check" in sys.argv
for path, content in outputs.items():
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit("Contract drift: " + str(path))
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
print("Contracts verified" if check else "Contracts generated")
